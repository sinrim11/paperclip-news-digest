/**
 * trade-key.ts — 실거래를 단지에 붙일 때 쓰는 조인 키 (2026-08-29).
 *
 * 이름만으로 묶으면 '현대'·'삼성' 같은 흔한 단지명이 여러 지역의 거래를 한 표본에 섞는다.
 * 지역(구·법정동)까지 좁히고, 표기 흔들림('평내호평역 대명루첸' vs '평내호평역대명루첸아파트')은
 * 정규화로 흡수한다. 정규화를 넣으면 매칭이 536→626건으로 는다.
 */

export const normName = (s: string) => s.replace(/\s|아파트/g, '');

/**
 * 법정동 표기 정규화(2026-09-10) — 읍·면 지역에서 국토부는 '화도읍 창현리'(읍+리),
 * 네이버는 '화도읍'(읍만)으로 쓴다. 그대로 조인하면 읍면 단지가 조용히 미매칭된다.
 * 실측: 읍면+리 표기 200개 중 99개가 이 이유로 어긋났고, 정규화 후 키 충돌은 0건이었다.
 */
export const normDong = (d: string) => d.replace(/^(\S+[읍면])\s+\S+리$/, '$1');

/**
 * 외부 데이터셋 조인용 공격적 정규화(2026-09-12) — 하이픈·점·괄호를 지우고 소문자화.
 * 출처마다 '중흥S-클래스'/'중흥S클래스', '동아.삼익.풍림'/'동아삼익풍림'처럼 쓴다.
 * 실거래↔후보 조인(normName)에 같은 규칙을 쓰면 기존 매칭이 흔들리므로 분리해 둔다.
 */
export const loosName = (s: string) => normName(s).replace(/[-–—·.,()[\]/]/g, '').toLowerCase();

export const tradeKey = (gu: string, dong: string, name: string) => `${gu}|${normDong(dong)}|${normName(name)}`;
